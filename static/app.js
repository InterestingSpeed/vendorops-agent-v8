async function refreshApprovalIndicators(sourceRows=null){
  const rows = Array.isArray(sourceRows) ? sourceRows : await api('/api/approvals');
  const seen = new Set(getSeenApprovalIds().map(Number));
  unreadApprovalIds = rows.filter(r=>r.status==='PENDING' && !seen.has(Number(r.id))).map(r=>Number(r.id));
  const count = unreadApprovalIds.length;
  for(const id of ['sideApprovalBadge','tabApprovalBadge']){
    const el=$(id); if(!el) continue;
    el.textContent = count;
    el.classList.toggle('hidden', count===0);
  }
  const sideBtn=document.querySelector('.side-nav[data-tab="approvals"]');
  const tabBtn=document.querySelector('.tab[data-tab="approvals"]');
  sideBtn?.classList.toggle('has-alert', count>0);
  tabBtn?.classList.toggle('has-alert', count>0);
  return rows;
}
function markViewedApprovalsAsRead(){
  if(!viewedApprovalIds.length) return;
  const seen = new Set(getSeenApprovalIds().map(Number));
  viewedApprovalIds.forEach(id=>seen.add(Number(id)));
  setSeenApprovalIds([...seen]);
  viewedApprovalIds = [];
}
