function toolSummary(tool,result){
  result=result||{};
  if(tool==='llm_plan') return `${result.intent||'Task'} · ${result.reason||'Goal interpreted by the model'}`;
  if(tool==='inspect_uploaded_invoice') return result.ok?`${result.invoice_number||'Invoice'} · ${result.po_number||'No PO'} · ${money(result.amount)} · ${result.extraction_method||'parsed'}`:(result.message||'Document extraction needs review');
  if(tool==='verify_gstin'){const p=result.profile||{};return result.ok?`${p.registration_status||'Verified'} · ${p.trade_name||p.legal_name||p.gstin||''}`:(result.message||'GST verification failed');}
  if(tool==='search_vendor'){const v=result.vendor||{};return result.found?`${v.vendor_code||''} · ${v.trade_name||v.legal_name||''} · ${v.status||''}`:'No vendor record found';}
  if(tool==='search_purchase_order'){const p=result.purchase_order||{};return result.found?`${p.po_number||''} · ${p.status||''} · PO value ${money(p.total_amount)} · consumed ${money(p.amount_consumed)}`:'Purchase order not found';}
  if(tool==='find_duplicate_invoice') return result.duplicate?'Potential duplicate found':'No duplicate invoice found';
  if(tool==='get_policy'){const p=result.policy||{};return p.policy_key?`${p.policy_key} = ${p.value_text}`:'Policy checked';}
  if(tool==='create_provisional_vendor'){const v=result.vendor||{};return `${v.vendor_code||'Vendor'} · ${v.trade_name||''} · ${v.status||'PROVISIONAL'}`;}
  if(tool==='request_human_approval'){const a=result.approval||{};const ex=approvalExplanation(a);return `Approval ${a.id?'#'+a.id:''} · ${a.approval_type||'REVIEW'} — ${ex.why}`;}
  if(tool==='send_notification') return result.ok?'Notification persisted to outbox':'Notification failed';
  if(tool==='create_gate_entry'){const g=result.gate_entry||{};return result.ok?`${g.gate_entry_number||'Gate entry'} · created and ${result.verified?'verified':'saved'}`:(result.message||'Gate entry rejected');}
  if(tool==='list_gate_entries') return `${result.count||0} gate entries returned`;
  if(tool==='list_pending_approvals') return `${result.count||0} pending approvals returned`;
  return result.message || (result.ok===false?'Action failed':'Action completed');
}
