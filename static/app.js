function renderTable(){
  const q=$('tableSearch').value.trim().toLowerCase();
  const rows=currentRows.filter(r=>!q || JSON.stringify(r).toLowerCase().includes(q));
  $('rowCount').textContent=`${rows.length} record${rows.length===1?'':'s'}`;
  if(!rows.length){$('tableWrap').innerHTML='<div class="table-empty">No matching records in this view.</div>';return;}
  const cols=columnsFor(currentTab,rows);
  const head=cols.map(k=>`<th>${esc(labelKey(k))}</th>`).join('');
  const body=rows.map(r=>{
    const isUnreadApproval=currentTab==='approvals' && r.status==='PENDING' && unreadApprovalIds.includes(Number(r.id));
    const rowCls=isUnreadApproval?' class="unread-approval-row"':'';
    const rowAttrs=currentTab==='approvals'?` data-approval-id="${r.id}"`:'';
    return `<tr${rowCls}${rowAttrs}>${cols.map(k=>{
      if(k==='actions'){
        if(r.status==='PENDING') return `<td><div class="approval-actions"><button class="btn btn-primary" onclick="decide(${r.id},'APPROVED')">Approve</button><button class="btn btn-danger" onclick="decide(${r.id},'REJECTED')">Reject</button></div></td>`;
        return '<td>—</td>';
      }
      return `<td>${formatCell(k,r[k],r)}</td>`;
    }).join('')}</tr>`;
  }).join('');
  $('tableWrap').innerHTML=`<table class="data-table ${currentTab==='approvals'?'approvals-table':''}"><thead><tr>${head}</tr></thead><tbody>${body}</tbody></table>`;
}

