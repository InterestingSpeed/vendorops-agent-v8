function formatCell(key,v,row){
  if(v===null||v===undefined||v==='') return '<span style="color:#9aa8b5">—</span>';
  if(['status','registration_status'].includes(key)) return statusBadge(v);
  if(['bank_verified','procurement_approved'].includes(key)) return boolBadge(v);
  if(['total_amount','amount_consumed','amount'].includes(key)) return `<span class="money">${esc(money(v))}</span>`;
  if(['gstin','po_number','invoice_number','gate_entry_number','vendor_code','vehicle_number','policy_key'].includes(key)) return `<span class="mono cell-primary">${esc(v)}</span>`;
  if(key==='confidence_pct') return `${esc(v)}%`;
  if(key==='created_at'||key==='requested_at'||key==='decided_at'||key==='verified_at') return `<span class="mono">${esc(String(v).replace('T',' ').replace('+00:00',' UTC'))}</span>`;
  if(key==='details') return `<details class="inline-details"><summary>View execution details</summary><pre>${esc(JSON.stringify(v,null,2))}</pre></details>`;
  if(key==='reason') return `<div class="approval-reason"><span class="reason-icon">!</span><span>${esc(v)}</span></div>`;
  if(key==='review_context') return renderReviewContext(v,row);
  return esc(typeof v==='object'?JSON.stringify(v):v);
}

