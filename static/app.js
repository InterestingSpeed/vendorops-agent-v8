function statusBadge(v){
  const s=String(v??'').toUpperCase();
  const good=['APPROVED','ACTIVE','OPEN','CREATED','SENT','OK','COMPLETE','GATE_CREATED'];
  const bad=['BLOCKED','CANCELLED','REJECTED','FAILED','ERROR'];
  const warn=['PROVISIONAL','PENDING','HUMAN_REQUIRED','CLOSED'];
  const cls=good.includes(s)?'good':bad.includes(s)?'bad':warn.includes(s)?'warn':'neutral';
  return `<span class="badge ${cls}">${esc(v)}</span>`;
}
function boolBadge(v){ return Number(v)===1 ? '<span class="badge good">YES</span>' : '<span class="badge neutral">NO</span>'; }

